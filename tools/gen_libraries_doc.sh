#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# gen_libraries_doc.sh -- regenerate docs/LIBRARIES.md from the profile data.
#
# Written by a script rather than by hand on purpose.  A hand-maintained table
# of "which library can PseudoForge generate" drifts the moment a profile
# changes, and a stale table is worse than none: it makes promises the tool no
# longer keeps.  This reads data/profiles and reports what is actually true.
#
#   tools/gen_libraries_doc.sh [> docs/LIBRARIES.md]
# ---------------------------------------------------------------------------
set -uo pipefail

HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
export PF_ROOT=$HERE PF_LIB=$HERE/lib PF_DATA=$HERE/data
for m in core sink config deps elements xc namelist profiles metadata formats gth sssp convert doctor params engines; do
    . "$PF_LIB/$m.sh"
done
NO_COLOR=1 C_BOLD='' C_RESET='' C_DIM='' C_RED='' C_GREEN='' C_YELLOW='' C_BLUE='' C_CYAN=''
pf_config_defaults
# Load the user's rc as well, not just the defaults.  Without it ENGINE_ROOT
# paths are unset, params_have() cannot see the decks that ship inside the
# engine source trees, and libraries that PseudoForge can genuinely generate --
# FHI and Vanderbilt among them -- are documented as "download".  A generated
# table that understates the tool is as wrong as one that overstates it.
pf_config_load 2>/dev/null || true
pf_elements_load; pf_xc_load
pf_profiles_load; pf_metadata_load; pf_params_load; pf_engines_load
spec_init 2>/dev/null || true

bundled_size() {
    # PSlibrary recipes are shipped under data/psl, everything else under
    # data/params; report whichever actually holds this profile's data.
    case $1 in
        # HGH is the relativistic half of the GTH tables and ships inside the
        # same directory; reporting "-" for it would suggest nothing is bundled.
        hgh)   local d=$PF_DATA/params/cp2k-gth
               [ -d "$d" ] && { du -sh "$d" 2>/dev/null | cut -f1; return; } ;;
        psl-*) local set; set=$(prof_psl_set "$1" paw)
               [ -n "$set" ] || set=$(prof_psl_set "$1" nc)
               if [ -n "$set" ] && [ -d "$PF_DATA/psl/$set" ]; then
                   du -sh "$PF_DATA/psl/$set" 2>/dev/null | cut -f1; return
               fi ;;
    esac
    local d=$PF_DATA/params/$1
    [ -d "$d" ] || { printf -- '-\n'; return; }
    du -sh "$d" 2>/dev/null | cut -f1
}

cat <<'HEAD'
# Libraries

Every pseudopotential library PseudoForge knows about, what it can do with
each, and why.  Generated by `tools/gen_libraries_doc.sh` from `data/profiles`,
so it describes the tool as it actually is rather than as it was documented.

## How to read the "PseudoForge can" column

| value | meaning |
|---|---|
| **generate** | PseudoForge runs an atomic code locally using *that library's own published parameters*. The result is a reproduction, recorded with provenance `library`. |
| **derive** | PseudoForge constructs the parameters itself. Not a reproduction of anybody's library, and labelled that way in the file, the report and the file name. |
| **download** | The library is fetched and then validated, cutoff-scanned and reported on exactly like something generated here. |
| **import** | Same pipeline, but you supply the files: the library is not addressable by URL, or its parameters are not published. |

A library marked **download** or **import** rather than **generate** is not a
gap in the tool.  It means the numbers that define that library are not
published, and PseudoForge will not invent them and put someone else's name on
the result.

HEAD

printf '## Summary\n\n'
printf '| library | type | functionals | PseudoForge can | engine | bundled |\n'
printf '|---|---|---|---|---|---|\n'
for id in $(prof_list); do
    fams=${PROF_FAMILIES[$id]:-}
    eng=$(eng_for_profile "$id" "${fams%% *}" 2>/dev/null)
    case $(prof_badge "$id") in
        generated|generatable) can="generate" ;;
        derived)               can="derive" ;;
        selection)             can="select" ;;
        analytic)              can="use directly" ;;
        *) if [ -n "${MD_OFFICIAL_URL[$id]:-}" ]; then can="download"; else can="import"; fi ;;
    esac
    printf '| **%s** | %s | %s | %s | %s | %s |\n' \
        "${PROF_LABEL[$id]}" "$(upper "$fams")" "${PROF_XC[$id]:-?}" "$can" \
        "${ENG_LABEL[$eng]:-n/a}" "$(bundled_size "$id")"
done

printf '\n## Detail\n\n'
for id in $(prof_list); do
    printf '### %s\n\n' "${PROF_LABEL[$id]}"
    printf -- '- **id** `%s`\n' "$id"
    printf -- '- **families** %s\n' "${PROF_FAMILIES[$id]:-n/a}"
    printf -- '- **generator** %s\n' "${PROF_GENERATOR[$id]:-n/a}"
    [ -n "${PROF_REFERENCE[$id]:-}" ] && printf -- '- **source** <%s>\n' "${PROF_REFERENCE[$id]}"
    printf -- '- **licence** %s\n' "$(md_license "$id")"
    [ -n "${PROF_AVAILABLE[$id]:-}" ] && printf -- '- **published** %s\n' "${PROF_AVAILABLE[$id]}"
    printf '\n%s\n' "${PROF_SUMMARY[$id]:-}"
    [ -n "${PROF_NOTES[$id]:-}" ] && printf '\n%s\n' "${PROF_NOTES[$id]}"
    local_cite=$(md_citation "$id")
    printf '\n**Cite:** %s\n\n' "$local_cite"
done

printf -- '---\n\nRegenerate with `tools/gen_libraries_doc.sh > docs/explanation/libraries.md`.\n'
