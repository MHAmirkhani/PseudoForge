/* ---------------------------------------------------------------------------
 * provenance.js -- frontend logic for the provenance viewer
 * ------------------------------------------------------------------------- */
'use strict';

(function () {
  const form = document.getElementById('prov-form');
  const input = document.getElementById('prov-input');
  const resultDiv = document.getElementById('prov-result');

  function esc(s) {
    if (s == null) return '';
    return String(s)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;');
  }

  function downloadText(filename, text) {
    const blob = new Blob([text], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  }

  async function loadProvenance(id) {
    if (!id) return;
    input.value = id;
    resultDiv.innerHTML = '<p class="muted">Loading provenance for <code>' + esc(id) + '</code>...</p>';

    try {
      const res = await API.provenance(id);
      if (res.status !== 200 || !res.body || res.body.error) {
        resultDiv.innerHTML =
          '<div class="prov-error"><strong>Error:</strong> ' +
          esc((res.body && res.body.message) || 'Provenance not found.') +
          '</div>';
        return;
      }

      const p = res.body;
      const elText = p.element ? `${p.element} (${p.element_name || ''}, Z=${p.z || '?'})` : '—';

      let html = '<div class="prov-card">';
      html += '<h2>' + esc(p.id) + '</h2>';
      html += '<hr class="prov-sep">';
      html += '<table class="prov-table"><tbody>';
      html += '<tr><th>Element</th><td>' + esc(elText) + '</td></tr>';
      html += '<tr><th>Family</th><td>' + esc(p.family) + '</td></tr>';
      html += '<tr><th>Functional</th><td>' + esc(p.functional) + '</td></tr>';
      html += '<tr><th>Relativity</th><td>' + esc(p.relativity) + '</td></tr>';
      html += '<tr><th>Profile</th><td>' + esc(p.profile) + '</td></tr>';
      html += '<tr><th>Engine</th><td>' + esc(p.engine) + '</td></tr>';
      html += '<tr><th>Binary SHA256</th><td><code>' + esc(p.binary_sha256) + '</code></td></tr>';
      html += '<tr><th>Build date</th><td>' + esc(p.build_date) + '</td></tr>';
      html += '<tr><th>Source</th><td>' + esc(p.source) + '</td></tr>';
      html += '<tr><th>Generated by</th><td><div class="prov-cmd">' + esc(p.generated_by) + '</div></td></tr>';
      html += '<tr><th>Format</th><td><code>' + esc(p.format) + '</code></td></tr>';
      html += '<tr><th>Size</th><td>' + esc(p.size) + ' bytes</td></tr>';
      html += '<tr><th>SHA256</th><td><code>' + esc(p.sha256) + '</code></td></tr>';
      html += '</tbody></table>';

      html += '<div class="prov-actions">';
      if (p.raw) {
        html += '<button type="button" class="btn" id="dl-prov-btn">Download PROVENANCE.txt</button>';
      }
      html += '<a class="btn primary" href="' + API.downloadUrl(p.id) + '">Download Pseudopotential</a>';
      html += '</div>';

      if (p.raw) {
        html += '<div class="prov-raw-box">';
        html += '<details><summary><strong>View Raw PROVENANCE.txt</strong></summary>';
        html += '<pre>' + esc(p.raw) + '</pre>';
        html += '</details></div>';
      }

      html += '</div>';

      resultDiv.innerHTML = html;

      const dlBtn = document.getElementById('dl-prov-btn');
      if (dlBtn && p.raw) {
        dlBtn.addEventListener('click', () => {
          downloadText('PROVENANCE.txt', p.raw);
        });
      }
    } catch (e) {
      resultDiv.innerHTML = '<div class="prov-error">Failed to load provenance: ' + esc(e.message) + '</div>';
    }
  }

  form.addEventListener('submit', (e) => {
    e.preventDefault();
    const val = input.value.trim();
    if (val) {
      const url = new URL(window.location);
      url.searchParams.set('id', val);
      window.history.pushState({}, '', url);
      loadProvenance(val);
    }
  });

  // Load from query string on entry
  const params = new URLSearchParams(window.location.search);
  const qId = params.get('id');
  if (qId) {
    loadProvenance(qId);
  }
})();
